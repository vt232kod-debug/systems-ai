# -*- coding: utf-8 -*-
"""
ЛР №4 (у методичці — ЛР №7). Частина А, Завдання 2.
Метод найменших квадратів (МНК) для ВАРІАНТА 3.
Камінський Олексій Дмитрович, ВТ-23-2, № у списку 3.

Варіант 3 таблиці варіантів:
    X: 7   12  17  22  27  32
    Y: 8    7   6   5   4   3

Параметри лінійної функції y = b0 + b1*x шукаємо ВРУЧНУ через нормальні рівняння МНК,
додатково перевіряємо numpy.linalg.solve, numpy.linalg.lstsq та numpy.polyfit.
"""

import matplotlib                       # імпорт matplotlib до pyplot, щоб задати backend
matplotlib.use("Agg")                   # неінтерактивний backend: малюємо у файл, без вікна
import matplotlib.pyplot as plt         # модуль побудови графіків
import numpy as np                      # бібліотека числових масивів

# ---------------------------------------------------------------- вхідні дані
# Експериментальні значення величини X (варіант 3)
X = np.array([7.0, 12.0, 17.0, 22.0, 27.0, 32.0])
# Експериментальні значення величини Y (варіант 3)
Y = np.array([8.0, 7.0, 6.0, 5.0, 4.0, 3.0])
n = len(X)                              # кількість експериментальних точок N = 6

print("=" * 70)
print("ЧАСТИНА А. ЗАВДАННЯ 1. КОНТРОЛЬ ТЕОРЕТИЧНОГО ПРИКЛАДУ МЕТОДИЧКИ")
print("=" * 70)
# Завдання 1 методички — опрацювати теоретичні відомості. Щоб опрацювання було
# перевіреним, а не декларативним, відтворюємо розібраний у методичці приклад:
# точки (1,6), (2,5), (3,7), (4,10) -> y = 3.5 + 1.4x, S(3.5, 1.4) = 4.2.
Xe = np.array([1.0, 2.0, 3.0, 4.0])    # абсциси чотирьох точок прикладу
Ye = np.array([6.0, 5.0, 7.0, 10.0])   # ординати чотирьох точок прикладу
ne = len(Xe)                           # кількість точок у прикладі (N = 4)
# Ті самі нормальні рівняння: D = n*Σx² - (Σx)², b1 = (n*Σxy - Σx*Σy)/D, b0 = (Σy - b1*Σx)/n
De = ne * (Xe * Xe).sum() - Xe.sum() ** 2                               # визначник системи
b1e = (ne * (Xe * Ye).sum() - Xe.sum() * Ye.sum()) / De                 # нахил прямої β1
b0e = (Ye.sum() - b1e * Xe.sum()) / ne                                  # зсув прямої β0
Se = ((Ye - (b0e + b1e * Xe)) ** 2).sum()                               # мінімум S(β0, β1)
print("Точки прикладу: (1,6), (2,5), (3,7), (4,10)")
print("  Σx = %.1f, Σy = %.1f, Σx² = %.1f, Σxy = %.1f"
      % (Xe.sum(), Ye.sum(), (Xe * Xe).sum(), (Xe * Ye).sum()))
print("  Нормальні рівняння дають: β0 = %.4f, β1 = %.4f  => y = %.1f + %.1f·x"
      % (b0e, b1e, b0e, b1e))
print("  Залишки e_i =", np.round(Ye - (b0e + b1e * Xe), 4))
print("  Мінімальна сума квадратів похибок S(β0, β1) = %.4f" % Se)
print("  Очікування методички: β0 = 3.5, β1 = 1.4, S = 4.2 -> збіг: %s"
      % ("так" if (abs(b0e - 3.5) < 1e-12 and abs(b1e - 1.4) < 1e-12
                   and abs(Se - 4.2) < 1e-12) else "ні"))

print()
print("=" * 70)
print("ЧАСТИНА А. ЗАВДАННЯ 2. МЕТОД НАЙМЕНШИХ КВАДРАТІВ, ВАРІАНТ 3")
print("=" * 70)
print("Вхідні дані (N = %d):" % n)
print("  X =", X)
print("  Y =", Y)

# ------------------------------------------------- 1) проміжні суми МНК вручну
# МНК мінімізує S(b0,b1) = sum( y_i - (b0 + b1*x_i) )^2.
# Прирівнявши часткові похідні dS/db0 = 0 і dS/db1 = 0, отримуємо нормальні рівняння:
#   n*b0    + (Σx)*b1  = Σy
#   (Σx)*b0 + (Σx²)*b1 = Σxy
sum_x = X.sum()                         # Σx  — сума значень x
sum_y = Y.sum()                         # Σy  — сума значень y
sum_xx = (X * X).sum()                  # Σx² — сума квадратів x
sum_xy = (X * Y).sum()                  # Σxy — сума добутків x*y
sum_yy = (Y * Y).sum()                  # Σy² — потрібна для оцінки розсіювання

print("\n1) Проміжні суми для нормальних рівнянь:")
print("   Σx   = %.4f" % sum_x)
print("   Σy   = %.4f" % sum_y)
print("   Σx²  = %.4f" % sum_xx)
print("   Σxy  = %.4f" % sum_xy)
print("   Σy²  = %.4f" % sum_yy)

# Таблиця проміжних обчислень по кожній точці — для звіту
print("\n   Таблиця проміжних обчислень:")
print("   %3s %8s %8s %10s %10s" % ("i", "x_i", "y_i", "x_i^2", "x_i*y_i"))
for i in range(n):                      # проходимо всі експериментальні точки
    print("   %3d %8.2f %8.2f %10.2f %10.2f" % (i + 1, X[i], Y[i], X[i] ** 2, X[i] * Y[i]))

# ------------------------------------------- 2) розв'язок нормальних рівнянь
# Визначник системи нормальних рівнянь: D = n*Σx² - (Σx)²
D = n * sum_xx - sum_x ** 2
# Коефіцієнт нахилу: b1 = (n*Σxy - Σx*Σy) / D
b1 = (n * sum_xy - sum_x * sum_y) / D
# Коефіцієнт зсуву: b0 = (Σy - b1*Σx) / n
b0 = (sum_y - b1 * sum_x) / n

print("\n2) Розв'язок нормальних рівнянь (ручний розрахунок):")
print("   D  = n*Σx² - (Σx)² = %d*%.2f - %.2f² = %.4f" % (n, sum_xx, sum_x, D))
print("   b1 = (n*Σxy - Σx*Σy)/D = (%d*%.2f - %.2f*%.2f)/%.2f = %.6f"
      % (n, sum_xy, sum_x, sum_y, D, b1))
print("   b0 = (Σy - b1*Σx)/n = (%.2f - (%.6f)*%.2f)/%d = %.6f"
      % (sum_y, b1, sum_x, n, b0))
print("   => y = %.6f + (%.6f)*x" % (b0, b1))

# -------------------------------------------- 3) перевірка засобами numpy
# Матриця системи нормальних рівнянь A та правий вектор b
A = np.array([[n, sum_x], [sum_x, sum_xx]])
rhs = np.array([sum_y, sum_xy])
beta_solve = np.linalg.solve(A, rhs)    # прямий розв'язок системи 2x2

# Той самий результат через переозначену матрицю плану M (МНК у матричній формі)
M = np.vstack([np.ones(n), X]).T        # матриця плану: стовпець одиниць + стовпець x
beta_lstsq = np.linalg.lstsq(M, Y, rcond=None)[0]   # розв'язок задачі найменших квадратів
beta_polyfit = np.polyfit(X, Y, 1)      # polyfit повертає [b1, b0] — порядок зворотний

print("\n3) Перевірка іншими засобами:")
print("   numpy.linalg.solve  -> b0 = %.6f, b1 = %.6f" % (beta_solve[0], beta_solve[1]))
print("   numpy.linalg.lstsq  -> b0 = %.6f, b1 = %.6f" % (beta_lstsq[0], beta_lstsq[1]))
print("   numpy.polyfit(1)    -> b0 = %.6f, b1 = %.6f" % (beta_polyfit[1], beta_polyfit[0]))

# ----------------------------------------------- 4) якість апроксимації
Y_fit = b0 + b1 * X                     # значення апроксимуючої функції у вузлах
residuals = Y - Y_fit                   # залишки (похибки) e_i = y_i - ŷ_i
S = (residuals ** 2).sum()              # мінімальна сума квадратів похибок S(b0,b1)
SS_tot = ((Y - Y.mean()) ** 2).sum()    # повна сума квадратів відхилень від середнього
R2 = 1.0 - S / SS_tot                   # коефіцієнт детермінації R²
rmse = np.sqrt(S / n)                   # середньоквадратична похибка

print("\n4) Якість апроксимації:")
print("   Залишки e_i =", np.round(residuals, 12))
print("   S(b0,b1) = Σe² = %.12f" % S)
print("   RMSE     = %.12f" % rmse)
print("   R²       = %.12f" % R2)

# Додатково: квадратична апроксимація — щоб показати, що лінійна моделі достатньо
c2 = np.polyfit(X, Y, 2)                # коефіцієнти параболи y = c2[0]x² + c2[1]x + c2[2]
S2 = ((Y - np.polyval(c2, X)) ** 2).sum()   # сума квадратів похибок параболи
print("\n   Контроль: квадратична МНК-апроксимація y = %.3ex² + %.6fx + %.6f, S = %.3e"
      % (c2[0], c2[1], c2[2], S2))
print("   Квадратичний член практично нульовий => дані лежать точно на прямій.")

# --------------------------------------------------------- 5) побудова графіка
x_grid = np.linspace(X.min() - 2, X.max() + 2, 300)   # щільна сітка для гладкої кривої
y_grid = b0 + b1 * x_grid                              # значення апроксимуючої прямої

fig, ax = plt.subplots(figsize=(8, 5.5))               # створюємо полотно і вісі
ax.plot(x_grid, y_grid, color="crimson", linewidth=2,  # апроксимуюча функція
        label="Апроксимуюча пряма: y = %.2f %+.2f·x" % (b0, b1))
ax.scatter(X, Y, s=90, color="royalblue", edgecolors="black",   # експериментальні точки
           zorder=5, label="Експериментальні точки")
for xi, yi in zip(X, Y):                               # підписуємо кожну точку
    ax.annotate("(%g; %g)" % (xi, yi), (xi, yi), textcoords="offset points",
                xytext=(6, 8), fontsize=8)
ax.set_xlabel("X")                                     # підпис осі абсцис
ax.set_ylabel("Y")                                     # підпис осі ординат
ax.set_title("Частина А, завдання 2: МНК, варіант 3 (R² = %.4f, S = %.2e)" % (R2, S))
ax.grid(True, linestyle="--", alpha=0.5)               # допоміжна сітка
ax.legend()                                            # легенда
fig.tight_layout()                                     # прибираємо зайві поля
fig.savefig("fig1_mnk_variant3.png", dpi=150)          # зберігаємо рисунок у PNG
plt.close(fig)                                         # звільняємо пам'ять

print("\nРисунок збережено: fig1_mnk_variant3.png")
print("ВІДПОВІДЬ: y = %.4f %+.4f·x" % (b0, b1))
