# -*- coding: utf-8 -*-
"""
ЛР №4. Частина А, Завдання 3. Інтерполяція функції, заданої таблично у 5 точках.
Камінський Олексій Дмитрович, ВТ-23-2.

Вектори даних (однакові для всіх варіантів):
    x = [0.1, 0.3, 0.4, 0.6, 0.7]
    y = [3.2, 3.0, 1.0, 1.8, 1.9]

Алгоритм за методичкою:
  1. Заповнення матриці X (матриця Вандермонда);
  2. Отримання коефіцієнтів інтерполяційного полінома (розв'язок X*A = Y);
  3. Визначення функції полінома (степінь 4);
  4. Побудова графіка інтерполюючого полінома;
  5. Обчислення значень функції у проміжних точках 0.2 та 0.5.
"""

import matplotlib                       # налаштування backend перед pyplot
matplotlib.use("Agg")                   # малюємо у файл, вікно не відкриваємо
import matplotlib.pyplot as plt         # побудова графіків
import numpy as np                      # числові масиви та лінійна алгебра

# ------------------------------------------------------- вхідні табличні дані
x = np.array([0.1, 0.3, 0.4, 0.6, 0.7])        # вузли інтерполяції x_i
y = np.array([3.2, 3.0, 1.0, 1.8, 1.9])        # значення функції f(x_i)
n = len(x)                                     # кількість вузлів = 5
m = n - 1                                      # степінь полінома = 4 (n-1)

print("=" * 70)
print("ЧАСТИНА А. ЗАВДАННЯ 3. ІНТЕРПОЛЯЦІЯ ПОЛІНОМОМ 4-го СТЕПЕНЯ")
print("=" * 70)
print("Вузли інтерполяції:")
for i in range(n):                             # виводимо таблицю вузлів
    print("   x[%d] = %.1f   y[%d] = %.1f" % (i, x[i], i, y[i]))
print("Кількість вузлів n = %d  =>  степінь полінома m = %d" % (n, m))

# ------------------------------------------- 1) заповнення матриці X (Вандермонда)
# Рядок i матриці: [1, x_i, x_i², x_i³, x_i⁴]; стовпці — степені змінної x.
Xmat = np.zeros((n, m + 1))                    # заготовка матриці 5x5, заповнена нулями
for i in range(n):                             # цикл по рядках (вузлах)
    for j in range(m + 1):                     # цикл по стовпцях (степенях)
        Xmat[i, j] = x[i] ** j                 # елемент X[i][j] = x_i^j

print("\n1) Матриця X (Вандермонда), рядок = [1, x, x², x³, x⁴]:")
for i in range(n):                             # друкуємо матрицю рядок за рядком
    print("   [" + "  ".join("%10.6f" % v for v in Xmat[i]) + " ]")

# Визначник Вандермонда — має бути відмінний від нуля (умова єдиності розв'язку)
detX = np.linalg.det(Xmat)
print("   Визначник Вандермонда Δ = %.6e  (Δ ≠ 0 => розв'язок єдиний)" % detX)

# ------------------------------------- 2) отримання коефіцієнтів полінома (X*A = Y)
A = np.linalg.solve(Xmat, y)                   # розв'язуємо СЛАР 5x5 відносно a0..a4

print("\n2) Коефіцієнти інтерполяційного полінома (розв'язок X·A = Y):")
for j in range(m + 1):                         # виводимо кожний коефіцієнт
    print("   a%d = %14.6f" % (j, A[j]))

# Контроль через numpy.polyfit: той самий поліном, але коефіцієнти в порядку спадання
A_polyfit = np.polyfit(x, y, m)                # [a4, a3, a2, a1, a0]
print("   Контроль numpy.polyfit:", np.round(A_polyfit[::-1], 6))

# ------------------------------------------------- 3) визначення функції полінома
def P(t):
    """Значення інтерполяційного полінома P4(t) = a0 + a1*t + a2*t² + a3*t³ + a4*t⁴."""
    t = np.asarray(t, dtype=float)             # приводимо аргумент до масиву float
    s = np.zeros_like(t)                       # накопичувач суми, тієї ж форми
    for j in range(m + 1):                     # додаємо доданок a_j * t^j
        s = s + A[j] * t ** j
    return s                                   # повертаємо значення полінома

# Запис полінома у вигляді формули — для звіту
terms = ["%+.6f" % A[0]]                       # вільний член
for j in range(1, m + 1):                      # решта доданків із степенями
    terms.append("%+.6f·x^%d" % (A[j], j))
print("\n3) P4(x) = " + " ".join(terms))

# Перевірка умови інтерполяції P(x_i) = y_i у всіх вузлах
print("   Перевірка умови інтерполяції P4(x_i) = y_i:")
for i in range(n):                             # проходимо всі вузли
    print("     P4(%.1f) = %12.9f   y_i = %.1f   різниця = %.2e"
          % (x[i], P(x[i]), y[i], P(x[i]) - y[i]))
max_err = np.max(np.abs(P(x) - y))             # максимальна нев'язка у вузлах
print("   Максимальна нев'язка у вузлах: %.3e" % max_err)

# ------------------------- 5) значення функції у проміжних точках 0.2 та 0.5
x_mid = np.array([0.2, 0.5])                   # проміжні точки за умовою завдання
y_mid = P(x_mid)                               # значення полінома в цих точках

print("\n5) Значення функції у проміжних точках:")
print("   P4(0.2) = %.6f" % y_mid[0])
print("   P4(0.5) = %.6f" % y_mid[1])

# --------------------------------------------------------- 4) побудова графіка
x_grid = np.linspace(0.05, 0.75, 500)          # щільна сітка на відрізку [0.05; 0.75]
y_grid = P(x_grid)                             # значення полінома на сітці

fig, ax = plt.subplots(figsize=(8.5, 5.5))     # полотно і система координат
ax.plot(x_grid, y_grid, color="crimson", linewidth=2,          # інтерполяційний поліном
        label="Інтерполяційний поліном P₄(x)")
ax.scatter(x, y, s=100, color="royalblue", edgecolors="black", # вузли інтерполяції
           zorder=5, label="Вузли інтерполяції")
ax.scatter(x_mid, y_mid, s=120, marker="D", color="limegreen", # проміжні точки
           edgecolors="black", zorder=6, label="Проміжні точки 0.2 та 0.5")
for xi, yi in zip(x, y):                       # підписи вузлів
    ax.annotate("(%g; %g)" % (xi, yi), (xi, yi), textcoords="offset points",
                xytext=(6, 8), fontsize=8)
for xi, yi in zip(x_mid, y_mid):               # підписи проміжних точок
    ax.annotate("(%g; %.3f)" % (xi, yi), (xi, yi), textcoords="offset points",
                xytext=(6, -14), fontsize=8, color="darkgreen")
ax.set_xlabel("x")                             # підпис осі x
ax.set_ylabel("y")                             # підпис осі y
ax.set_title("Частина А, завдання 3: інтерполяція поліномом 4-го степеня")
ax.grid(True, linestyle="--", alpha=0.5)       # сітка
ax.legend()                                    # легенда
fig.tight_layout()                             # компактні поля
fig.savefig("fig2_interp_poly4.png", dpi=150)  # збереження у PNG
plt.close(fig)                                 # закриваємо фігуру

print("\nРисунок збережено: fig2_interp_poly4.png")
