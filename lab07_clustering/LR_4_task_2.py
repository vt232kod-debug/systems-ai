import matplotlib                                            # пакет побудови графіків
matplotlib.use("Agg")                                        # бекенд без вікна — малюємо у PNG-файл

import numpy as np                                           # масиви, генератор випадкових чисел
import matplotlib.pyplot as plt                              # інтерфейс малювання (у підказці НЕ імпортовано)
from sklearn.datasets import load_iris                       # завантажувач набору Iris (у підказці НЕ імпортовано)
from sklearn.cluster import KMeans                           # алгоритм k-середніх (у підказці НЕ імпортовано)
from sklearn.metrics import pairwise_distances_argmin        # індекс найближчого центру для кожної точки
from sklearn.metrics import accuracy_score, confusion_matrix # метрики порівняння міток з істинними класами
from sklearn.metrics import silhouette_score                 # оцінка якості кластеризації
from scipy.stats import mode                                 # мода — для зіставлення номерів кластерів з класами

# ===========================================================================
# 1. ЗАВАНТАЖЕННЯ ДАНИХ
# ===========================================================================
iris = load_iris()                       # об'єкт Bunch з полями data, target, feature_names, target_names
X = iris['data']                         # матриця ознак 150x4 (у підказці були «розумні» лапки ‘data’)
y = iris['target']                       # вектор істинних міток класів 0/1/2 (лише для перевірки якості)

print("Розмір матриці ознак X:", X.shape)                    # очікуємо (150, 4)
print("Назви ознак:", list(iris['feature_names']))           # перелік 4 ознак
# map(str, ...) потрібен, бо NumPy 2.x друкує елементи масиву як np.str_('setosa')
print("Назви класів:", list(map(str, iris['target_names'])))  # setosa / versicolor / virginica
print("Кількість зразків у кожному класі:", np.bincount(y))  # по 50 зразків на клас

# ===========================================================================
# 2. МОДЕЛЬ KMeans З ЯВНИМИ ПАРАМЕТРАМИ
# У методичці тут був виклик sklearn.cluster.KMeans(...) без присвоєння
# (результат нікуди не зберігався) та з параметрами, яких більше немає в API.
# ===========================================================================
# n_clusters=3   — три кластери, бо в Iris рівно три класи (у підказці було 8, потім 5 — помилка)
# init='k-means++' — покращена ініціалізація центроїдів (у підказці: 'k-means + +' з пробілами — невалідно)
# n_init=10      — 10 незалежних запусків, обирається найкращий за inertia
# max_iter=300   — максимум ітерацій уточнення центроїдів
# tol=0.0001     — поріг зупинки за зміщенням центроїдів
# verbose=0      — без службового виводу
# random_state=3 — фіксуємо генератор (номер варіанта) заради відтворюваності
# copy_x=True    — не змінювати вхідний масив X
# algorithm='lloyd' — класичний алгоритм Ллойда (замість застарілого 'auto')
# ПАРАМЕТРИ precompute_distances та n_jobs ВИДАЛЕНО з scikit-learn — їх прибрано.
kmeans = KMeans(n_clusters=3,            # кількість кластерів = кількості класів Iris
                init='k-means++',        # алгоритмічний вибір стартових центроїдів
                n_init=10,               # скільки разів перезапустити алгоритм
                max_iter=300,            # ліміт ітерацій одного запуску
                tol=0.0001,              # критерій збіжності
                verbose=0,               # тихий режим
                random_state=3,          # відтворюваність (варіант 3)
                copy_x=True,             # працювати з копією даних
                algorithm='lloyd')       # класичний метод Ллойда

kmeans.fit(X)                            # навчання моделі: пошук положень трьох центроїдів
y_kmeans = kmeans.predict(X)             # передбачення номера кластера для кожного з 150 зразків

print("\nЦентри кластерів (4 ознаки):")                      # заголовок виводу
for i, c in enumerate(kmeans.cluster_centers_):              # перебираємо знайдені центроїди
    print("  Кластер {}: {}".format(i, np.round(c, 4)))      # друкуємо округлені координати центру

# ===========================================================================
# 3. РИСУНОК 4. Кластери KMeans у площині перших двох ознак
# ===========================================================================
plt.figure(figsize=(7, 5))                                   # нове полотно заданого розміру
plt.scatter(X[:, 0], X[:, 1], c=y_kmeans, s=50, cmap='viridis')  # точки, колір = номер кластера
centers = kmeans.cluster_centers_                            # матриця центрів кластерів 3x4
plt.scatter(centers[:, 0], centers[:, 1], c='black', s=200, alpha=0.5)  # центри — великі напівпрозорі кружечки
plt.xlabel(iris['feature_names'][0])                         # підпис осі X — довжина чашолистка
plt.ylabel(iris['feature_names'][1])                         # підпис осі Y — ширина чашолистка
plt.title("KMeans (k=3) на наборі Iris")                     # заголовок рисунка
plt.grid(alpha=0.3)                                          # легка сітка для читабельності
plt.savefig("fig4_iris_kmeans.png", dpi=150, bbox_inches="tight")  # збереження у файл
plt.close()                                                  # закриваємо полотно, звільняємо пам'ять

# ===========================================================================
# 4. ВЛАСНА РЕАЛІЗАЦІЯ k-середніх через pairwise_distances_argmin
# ===========================================================================
def find_clusters(X, n_clusters, rseed=2):                   # власна функція k-середніх
    rng = np.random.RandomState(rseed)                       # окремий генератор випадкових чисел із зерном rseed
    i = rng.permutation(X.shape[0])[:n_clusters]             # випадкова перестановка індексів, беремо перші n_clusters
    centers = X[i]                                           # стартові центри = випадково обрані точки даних
    while True:                                              # ітеративний процес до збіжності
        labels = pairwise_distances_argmin(X, centers)       # кожній точці — індекс найближчого центру
        new_centers = np.array([X[labels == i].mean(0)       # новий центр = середнє точок свого кластера
                                for i in range(n_clusters)]) # по всіх кластерах
        if np.all(centers == new_centers):                   # якщо центри не зрушили — збіжність досягнута
            break                                            # виходимо з циклу
        centers = new_centers                                # інакше оновлюємо центри й повторюємо
    return centers, labels                                   # повертаємо фінальні центри та мітки


def purity(labels_true, labels_pred):                        # допоміжна функція: частка правильних зіставлень
    mapped = np.zeros_like(labels_pred)                      # масив під перейменовані мітки
    for k in np.unique(labels_pred):                         # для кожного знайденого кластера
        mask = labels_pred == k                              # маска точок цього кластера
        mapped[mask] = mode(labels_true[mask], keepdims=False).mode  # присвоюємо найчастіший істинний клас
    return accuracy_score(labels_true, mapped), mapped       # повертаємо точність і перейменовані мітки


# --- Запуск власної реалізації з різними зернами rseed -----------------------
print("\n" + "=" * 68)                                       # роздільник у виводі
print("ВПЛИВ ПОЧАТКОВОЇ ІНІЦІАЛІЗАЦІЇ (rseed) НА РЕЗУЛЬТАТ")  # заголовок блоку
print("=" * 68)                                              # нижня межа заголовка

seeds = [0, 1, 2, 3, 7, 13]                                  # набір зерен для експерименту
results = {}                                                 # словник для збереження результатів
for rs in seeds:                                             # перебираємо зерна
    c, lab = find_clusters(X, 3, rseed=rs)                   # запускаємо власний k-середніх
    acc, _ = purity(y, lab)                                  # оцінюємо збіг з істинними класами
    sil = silhouette_score(X, lab)                           # оцінюємо щільність кластерів
    inertia = sum(((X[lab == k] - c[k]) ** 2).sum()          # рахуємо сумарну внутрішньокластерну дисперсію
                  for k in range(3))                         # підсумовуємо по трьох кластерах
    results[rs] = (acc, sil, inertia, lab, c)                # зберігаємо все для рисунка
    print("  rseed = {:<3d} точність = {:.4f}   silhouette = {:.4f}   inertia = {:8.4f}"   # рядок звіту
          .format(rs, acc, sil, inertia))                    # підставляємо показники цього зерна

# --- Той самий експеримент для бібліотечного KMeans -------------------------
print("\nБібліотечний KMeans з різним random_state (n_init=10):")   # заголовок другого експерименту
for rs in seeds:                                             # ті самі зерна
    km = KMeans(n_clusters=3, n_init=10, random_state=rs).fit(X)  # навчаємо модель
    acc, _ = purity(y, km.labels_)                           # оцінюємо точність
    print("  random_state = {:<3d} точність = {:.4f}   inertia = {:8.4f}"   # рядок звіту
          .format(rs, acc, km.inertia_))                     # підставляємо показники цього зерна

# ===========================================================================
# 5. РИСУНОК 5. Порівняння результатів при різних rseed
# ===========================================================================
# Методичка наводить три окремі фрагменти побудови графіка: find_clusters(X, 3)
# із зерном за замовчуванням rseed=2, find_clusters(X, 3, rseed=0) та
# KMeans(3, random_state=0).fit_predict(X). Усі три покриті цим рисунком:
# перші два — панелями rseed=2 і rseed=0, третій — останньою панеллю.
fig, axes = plt.subplots(2, 4, figsize=(19, 8))              # сітка 2x4 підграфіків (6 зерен + бібліотечний KMeans)
for ax, rs in zip(axes.ravel(), seeds):                      # кожному підграфіку — своє зерно
    acc, sil, inertia, lab, c = results[rs]                  # дістаємо збережений результат
    ax.scatter(X[:, 0], X[:, 1], c=lab, s=40, cmap='viridis')  # точки, колір = знайдений кластер
    ax.scatter(c[:, 0], c[:, 1], c='red', s=180, marker='X')   # центри — червоні хрестики
    ax.set_title("find_clusters, rseed = {}\nточність = {:.3f}, inertia = {:.1f}".format(rs, acc, inertia),
                 fontsize=10)                                # заголовок із числовими показниками
    ax.set_xlabel(iris['feature_names'][0], fontsize=8)      # підпис осі X
    ax.set_ylabel(iris['feature_names'][1], fontsize=8)      # підпис осі Y
    ax.grid(alpha=0.3)                                       # сітка

# --- сьома панель: третій фрагмент підказки — бібліотечний KMeans(3, random_state=0) ---
ax_lib = axes.ravel()[len(seeds)]                            # наступний вільний підграфік
km0 = KMeans(3, random_state=0)                              # рівно як у методичці: KMeans(3, random_state=0)
lab0 = km0.fit_predict(X)                                    # мітки кластерів для всіх 150 зразків
acc0, _ = purity(y, lab0)                                    # точність відносно істинних класів
ax_lib.scatter(X[:, 0], X[:, 1], c=lab0, s=40, cmap='viridis')   # точки, колір = номер кластера
ax_lib.scatter(km0.cluster_centers_[:, 0], km0.cluster_centers_[:, 1],
               c='red', s=180, marker='X')                   # центри — червоні хрестики
ax_lib.set_title("KMeans(3, random_state=0)\nточність = {:.3f}, inertia = {:.1f}"
                 .format(acc0, km0.inertia_), fontsize=10)   # заголовок із показниками
ax_lib.set_xlabel(iris['feature_names'][0], fontsize=8)      # підпис осі X
ax_lib.set_ylabel(iris['feature_names'][1], fontsize=8)      # підпис осі Y
ax_lib.grid(alpha=0.3)                                       # сітка
axes.ravel()[-1].axis("off")                                 # восьма клітинка не використовується
print("\nKMeans(3, random_state=0) — третій фрагмент підказки: точність = {:.4f}, inertia = {:.4f}"
      .format(acc0, km0.inertia_))                           # те саме число у консоль

plt.suptitle("Вплив початкової ініціалізації: власна find_clusters проти бібліотечного KMeans", fontsize=13)
plt.tight_layout()                                           # прибираємо накладання підписів
plt.savefig("fig5_iris_rseed.png", dpi=150, bbox_inches="tight")  # зберігаємо рисунок
plt.close()                                                  # закриваємо полотно

# ===========================================================================
# 6. ПОРІВНЯННЯ З ІСТИННИМИ МІТКАМИ
# ===========================================================================
acc_km, mapped = purity(y, y_kmeans)                         # зіставляємо кластери KMeans з класами
print("\n" + "=" * 68)                                       # роздільник у виводі
print("ЯКІСТЬ КЛАСТЕРИЗАЦІЇ ВІДНОСНО ІСТИННИХ КЛАСІВ")        # заголовок блоку
print("=" * 68)                                              # нижня межа заголовка
print("Точність (після зіставлення кластер -> клас): {:.4f}".format(acc_km))   # частка збігів
print("Silhouette score: {:.4f}".format(silhouette_score(X, y_kmeans)))        # щільність кластерів
print("\nМатриця невідповідностей (рядки — істинний клас, стовпці — передбачений):")  # підпис матриці
print(confusion_matrix(y, mapped))                           # друкуємо матрицю плутанини

# --- Рисунок 6. Істинні класи проти знайдених кластерів ---------------------
fig, ax = plt.subplots(1, 2, figsize=(12, 4.5))              # два підграфіки поруч
ax[0].scatter(X[:, 2], X[:, 3], c=y, s=45, cmap='viridis')   # істинні класи в площині пелюстки
ax[0].set_title("Істинні класи Iris")                        # заголовок лівого графіка
ax[1].scatter(X[:, 2], X[:, 3], c=mapped, s=45, cmap='viridis')  # результат кластеризації
ax[1].set_title("Кластери KMeans (k=3), точність = {:.3f}".format(acc_km))  # заголовок правого
for a in ax:                                                 # однакове оформлення обох графіків
    a.set_xlabel(iris['feature_names'][2])                   # довжина пелюстки
    a.set_ylabel(iris['feature_names'][3])                   # ширина пелюстки
    a.grid(alpha=0.3)                                        # сітка
plt.tight_layout()                                           # компонування
plt.savefig("fig6_iris_true_vs_pred.png", dpi=150, bbox_inches="tight")  # зберігаємо
plt.close()                                                  # закриваємо

