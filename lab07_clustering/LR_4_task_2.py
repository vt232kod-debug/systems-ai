# 7. algorithm='auto' застаріло — замінено на 'lloyd'.
# 8. init='k-means + +' із пробілами — правильно 'k-means++'.
# 9. n_clusters=5 (а в прикладі вище 8) — для Iris має бути 3, бо класів три.
